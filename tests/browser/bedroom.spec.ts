import { expect, test } from "@playwright/test";
test("bedroom search survives save/reload, transfers a photo and reads its reverse on pause", async ({ page }) => {
    test.setTimeout(60000);
    const errors: string[] = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.goto("/");
    await expect(page.locator("#app")).toHaveAttribute("data-ready", "true");
    await expect(page.locator("#scene canvas")).toBeVisible();
    await expect(page.locator("#scene canvas")).toHaveAttribute("data-art", "raster-1.2");
    await page.screenshot({ path: "test-results/bedroom.png", fullPage: true });
    await page.getByRole("button", { name: "Продолжить", exact: true }).click();
    await page.keyboard.press("e");
    await expect(page.locator("#context")).toContainText("Тумбочка Соколовой");
    await page.getByRole("button", { name: "Обыскать · 5 с" }).click();
    await expect(page.getByTestId("action")).toContainText("Обыск");
    await page.getByRole("button", { name: "Пауза", exact: true }).click();
    const action = await page.getByTestId("action").textContent();
    await page.waitForTimeout(600);
    await expect(page.getByTestId("action")).toHaveText(action!);
    await page.getByText("Экспедиция и сохранения", { exact: true }).click();
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Сохранено локально");
    await page.reload();
    await expect(page.locator("#app")).toHaveAttribute("data-ready", "true");
    await page.getByText("Экспедиция и сохранения", { exact: true }).click();
    await page.getByRole("button", { name: "Загрузить", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Снимок загружен");
    await expect(page.getByTestId("action")).toHaveText(action!);
    await page.getByRole("button", { name: "Продолжить", exact: true }).click();
    await page.locator("#object-picker").selectOption("nightstand-left");
    await page.getByRole("button", { name: "Открыть вещи", exact: true }).click({ timeout: 9000 });
    const photo = page.locator("#source-items article").filter({ hasText: "Подписанная личная фотография" });
    await photo.getByRole("button", { name: "В рюкзак", exact: true }).click();
    await expect(page.locator("#bag-count")).toHaveText("1 / 10");
    await page.locator("#bag-items article").filter({ hasText: "Подписанная личная фотография" }).getByRole("button", { name: "В хранилище", exact: true }).click();
    await expect(page.locator("#bag-count")).toHaveText("0 / 10");
    await photo.getByRole("button", { name: "В рюкзак", exact: true }).click();
    await expect(page.locator("#bag-count")).toHaveText("1 / 10");
    await page.getByRole("button", { name: "Пауза", exact: true }).click();
    await page.locator("#bag-items article").filter({ hasText: "Подписанная личная фотография" }).getByRole("button", { name: "Читать", exact: true }).click();
    await expect(page.locator("#reader img")).toBeVisible();
    await expect.poll(() => page.locator("#reader img").evaluate((i: HTMLImageElement) => i.naturalWidth)).toBeGreaterThan(500);
    await page.screenshot({ path: "test-results/photo-reader.png", fullPage: true });
    await page.getByRole("button", { name: "Далее →", exact: true }).click();
    await expect(page.locator("#reader-body")).toContainText("Ире от Лёши");
    await expect(page.locator("#page-label")).toHaveText("Оборот");
    expect(errors).toEqual([]);
});
