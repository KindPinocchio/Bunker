import {expect,test} from "@playwright/test";
import {clickFloor} from "./motion-helpers";
import {loadContent} from "../../src/content/load";
import {Session} from "../../src/game/session";

test.use({viewport:{width:1280,height:1100},video:{mode:"on",size:{width:1280,height:1100}}});
test("walks continuously to the control room and runs local diagnostics",async({page})=>{
  test.setTimeout(90000);
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/");await expect(page.locator("#app")).toHaveAttribute("data-ready","true");
  const canvas=page.locator("#scene canvas"),door=page.locator("#control-door-controls");
  await expect(page.getByTestId("position")).toHaveText("4.00 / 2.50");
  await page.waitForTimeout(700);await page.getByRole("button",{name:"Продолжить",exact:true}).click();
  await page.locator("#bedroom-door-controls").getByRole("button",{name:"В коридор",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("4.00 / 1.50");
  for(const [x,y] of [[6,1.25],[9,1],[12,1],[15.5,.75]]){
    await clickFloor(page,x!,y!);await expect(page.getByTestId("position")).toHaveText(`${x!.toFixed(2)} / ${y!.toFixed(2)}`,{timeout:8000});
  }
  await door.getByRole("button",{name:"Закрыть",exact:true}).click();
  await expect(canvas).toHaveAttribute("data-control-door-state","closed");
  await expect(door.getByRole("button",{name:"В диспетчерскую",exact:true})).toBeDisabled();
  await door.getByRole("button",{name:"Открыть",exact:true}).click();
  await door.getByRole("button",{name:"В диспетчерскую",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("16.00 / -0.50");
  await expect(canvas).toHaveAttribute("data-room","u_control");
  await page.locator("#object-picker").selectOption("controller-console");
  await page.getByRole("button",{name:"Подойти",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("15.45 / -2.80",{timeout:8000});
  await page.screenshot({path:"test-results/control-room-arrival.png",fullPage:true});
  await page.getByRole("button",{name:"Открыть панель ЦБУ",exact:true}).click();
  const panel=page.getByRole("dialog",{name:"Панель ЦБУ",exact:true});
  await expect(panel.locator("tbody tr")).toHaveCount(17);
  await expect(panel).toContainText("Ключевой переключатель заблокирован");
  await expect(panel.getByTestId("cbu-result")).toContainText("ещё не выполнялась");
  await panel.getByRole("button",{name:"Самодиагностика · 5 с",exact:true}).click();
  await expect(page.getByTestId("action")).toContainText("Самодиагностика ЦБУ");
  await expect(panel.getByTestId("cbu-result")).toContainText("Повреждение ЦБУ",{timeout:8000});
  await page.screenshot({path:"test-results/controller-panel.png",fullPage:true});
  await page.getByRole("button",{name:"Закрыть панель ЦБУ",exact:true}).click();
  await door.getByRole("button",{name:"Подойти к двери",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("16.00 / -0.50",{timeout:8000});
  await door.getByRole("button",{name:"В коридор",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("16.00 / 0.50");
  await expect(canvas).toHaveAttribute("data-room","u_corridor");
  await page.getByRole("button",{name:"Пауза",exact:true}).click();await page.waitForTimeout(700);
  expect(errors).toEqual([]);
});

test("the panel shows signals, saves a paused diagnostic and loses remote access",async({page})=>{
  test.setTimeout(60000);
  await page.goto("/");await expect(page.locator("#app")).toHaveAttribute("data-ready","true");
  const snap=new Session(loadContent(),"controller-browser","bedroom").snapshot();
  Object.assign(snap.world.player,{roomId:"u_control",x:15.45,y:-2.8});
  snap.world.rooms.u_bed1!.temperatureC=99;snap.world.sensors.u_bed1_temp!.signal=12.5;snap.world.sensors.u_bed1_water!.signal=null;
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.locator("#import").setInputFiles({name:"controller.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(snap))});
  await expect(page.getByRole("status")).toContainText("Снимок загружен");
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.clock.install();
  const open=async()=>{await page.locator("#object-picker").selectOption("controller-console");await page.getByRole("button",{name:"Открыть панель ЦБУ",exact:true}).click();};
  await open();const panel=page.getByRole("dialog",{name:"Панель ЦБУ",exact:true});
  await expect(panel.locator('[data-room="u_bed1"]')).toContainText("12.5 °C");
  await expect(panel.locator('[data-room="u_bed1"]')).toContainText("НЕИСПР");
  await expect(panel).not.toContainText("99.0 °C");
  await expect(panel.getByRole("button",{name:"Самодиагностика · 5 с",exact:true})).toBeDisabled();
  await page.getByRole("button",{name:"Закрыть панель ЦБУ",exact:true}).click();
  await page.getByRole("button",{name:"Продолжить",exact:true}).click();await open();
  await panel.getByRole("button",{name:"Самодиагностика · 5 с",exact:true}).click();
  await page.clock.runFor(1200);await page.getByRole("button",{name:"Пауза",exact:true}).click();
  const remaining=await page.getByTestId("action").textContent();await page.clock.runFor(5000);
  await expect(page.getByTestId("action")).toHaveText(remaining!);
  await page.getByRole("button",{name:"Закрыть панель ЦБУ",exact:true}).click();
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(page.getByRole("status")).toContainText("Сохранено локально");
  await page.reload();await expect(page.locator("#app")).toHaveAttribute("data-ready","true");
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.getByRole("button",{name:"Загрузить",exact:true}).click();await expect(page.getByTestId("action")).toHaveText(remaining!);
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.clock.install();await page.getByRole("button",{name:"Продолжить",exact:true}).click();await open();await page.clock.runFor(4000);
  await expect(panel.getByTestId("cbu-result")).toContainText("Повреждение ЦБУ");
  await page.keyboard.down("s");await page.clock.runFor(1700);await page.keyboard.up("s");
  await expect(panel).toContainText("Подойдите к консоли ЦБУ");await expect(panel.locator("tbody tr")).toHaveCount(0);
});
