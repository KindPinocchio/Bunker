test.use({video:{mode:"on",size:{width:1280,height:900}}});
test("door blocks the player and hides the bedroom, round trip survives reload",async({page})=>{
  // Includes real-time walks, a reload and several full-page captures of the raster scene.
  test.setTimeout(75000);
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/");await expect(page.locator("#app")).toHaveAttribute("data-ready","true");
  const canvas=page.locator("#scene canvas"),controls=page.locator("#door-controls");
  await page.getByRole("button",{name:"Продолжить",exact:true}).click();
  await controls.getByRole("button",{name:"Закрыть",exact:true}).click();
  await expect(canvas).toHaveAttribute("data-door-state","closed");
  await expect(controls.getByRole("button",{name:"В коридор",exact:true})).toBeDisabled();
  await page.keyboard.down("w");await page.keyboard.down("d");await page.waitForTimeout(700);await page.keyboard.up("w");await page.keyboard.up("d");
  await expect(canvas).toHaveAttribute("data-room","u_bed1");
  expect(Number(await canvas.getAttribute("data-player-y"))).toBeGreaterThanOrEqual(2.16-1e-8);
  await page.screenshot({path:"test-results/door-closed-bedroom.png",fullPage:true});
  await controls.getByRole("button",{name:"Открыть",exact:true}).click();
  await controls.getByRole("button",{name:"В коридор",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("4.00 / 1.50");
  await expect(canvas).toHaveAttribute("data-room","u_corridor");
  await page.screenshot({path:"test-results/corridor-open.png",fullPage:true});
  await controls.getByRole("button",{name:"Закрыть",exact:true}).click();
  await expect(canvas).toHaveAttribute("data-visible-objects","");
  await expect(page.locator("#object-picker option")).toHaveCount(1);
  await expect(page.locator("#context")).not.toContainText("Тумбочка");
  await page.screenshot({path:"test-results/corridor-closed.png",fullPage:true});
  await page.getByRole("button",{name:/Фонарь · выкл/}).click();
  await page.getByRole("button",{name:"Пауза",exact:true}).click();
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(page.getByRole("status")).toContainText("Сохранено локально");
  await page.reload();await expect(page.locator("#app")).toHaveAttribute("data-ready","true");
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.getByRole("button",{name:"Загрузить",exact:true}).click();
  await expect(canvas).toHaveAttribute("data-room","u_corridor");await expect(canvas).toHaveAttribute("data-door-state","closed");await expect(canvas).toHaveAttribute("data-flashlight","true");
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.getByRole("button",{name:"Продолжить",exact:true}).click();
  await page.keyboard.down("s");await page.keyboard.down("d");await page.waitForTimeout(1400);await page.keyboard.up("s");await page.keyboard.up("d");
  await expect(canvas).toHaveAttribute("data-room","u_corridor");
  expect(Number(await canvas.getAttribute("data-player-x"))).toBeGreaterThan(5.5);
  await page.screenshot({path:"test-results/corridor-walk.png",fullPage:true});
  await controls.getByRole("button",{name:"Подойти к двери",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("4.00 / 1.50");
  await controls.getByRole("button",{name:"Авто",exact:true}).click();
  await expect(canvas).toHaveAttribute("data-door-state","open");
  await controls.getByRole("button",{name:"В спальню",exact:true}).click();
  await expect(page.getByTestId("position")).toHaveText("4.00 / 2.50");
  await expect(canvas).toHaveAttribute("data-room","u_bed1");
  await page.locator("#object-picker").selectOption("nightstand-left");
  await expect(page.locator("#context")).toContainText("Тумбочка Соколовой");
  await page.screenshot({path:"test-results/bedroom-return.png",fullPage:true});expect(errors).toEqual([]);
});

test("blackout renders black, flashlight reveals the floor and freezes on pause on mobile",async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto("/");
  await expect(page.locator("#app")).toHaveAttribute("data-ready","true");
  const content=loadContent(),session=new Session(content,"blackout-preview","bedroom");
  let world=applyDeveloperCommand(session.view(),{type:"external-line",available:false},content);
  world=applyDeveloperCommand(world,{type:"battery-output",enabled:false},content);
  const snapshot={...session.snapshot(),world};
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  await page.locator("#import").setInputFiles({name:"blackout.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(snapshot))});
  await expect(page.getByRole("status")).toContainText("Снимок загружен");
  await page.getByText("Экспедиция и сохранения",{exact:true}).click();
  const canvas=page.locator("#scene canvas");await expect(canvas).toHaveAttribute("data-light","0");
  const dark=await canvas.screenshot({path:"test-results/blackout-dark.png"});
  await page.getByRole("button",{name:"Продолжить",exact:true}).click();
  await page.getByRole("button",{name:/Фонарь · выкл/}).click();
  await expect(canvas).toHaveAttribute("data-flashlight","true");
  await expect(canvas).not.toHaveAttribute("data-visible-objects",/poster/);
  await page.getByRole("button",{name:"Пауза",exact:true}).click();
  await page.locator("#room-name").scrollIntoViewIfNeeded();
  const lit=await canvas.screenshot({path:"test-results/blackout-flashlight.png"});
  expect(lit.equals(dark),"Flashlight must change rendered pixels, not only its HUD state").toBe(false);
  await page.screenshot({path:"test-results/flashlight-mobile.png",fullPage:true});
  const position=await page.getByTestId("position").textContent();
  await page.keyboard.press("f");await page.waitForTimeout(200);
  await expect(canvas).toHaveAttribute("data-flashlight","true");await expect(page.getByTestId("position")).toHaveText(position!);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
